import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const migration = JSON.parse(await readFile(new URL('../data/route-migration.json', import.meta.url)));
const rules = new Map();
const add = (from, to) => { if (from !== to) { assert(!rules.has(from) || rules.get(from) === to, `Conflicting redirect ${from}`); rules.set(from, to); } };
add('/pj/zblanks', '/'); add('/pj/zblanks/', '/');
for (const { from, to, source } of migration.routes) {
  for (const old of [from, from.replace(/\/$/, '')]) {
    add(old, to); add('/pj/zblanks' + old, to);
  }
  if (/\/index\.mdx?$/.test(source)) {
    for (const alias of [from + 'index', from + 'index/']) { add(alias, to); add('/pj/zblanks' + alias, to); }
  }
}
for (const source of ['/assets/pcb-art/previews/index.html', '/assets/pcb-art/previews/', '/files/pcb-art/previews/index.html', '/files/pcb-art/previews/index.html/']) {
  add(source, '/viewers/pcb-art/'); add('/pj/zblanks' + source, '/viewers/pcb-art/');
}
// All other published raw assets retain their relative names and exact bytes.
add('/pj/zblanks/assets/*', '/assets/:splat');
add('/pj/zblanks/files/*', '/files/:splat');
add('/pj/zblanks/docs/claude*', '/docs/claude:splat');
const output = '# Generated by scripts/redirects.mjs. Queries are retained; fragments remain client-side.\n' + [...rules].map(([from,to]) => `${from} ${to} 301`).join('\n') + '\n';
const target = new URL('../public/_redirects', import.meta.url);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'Redirect drift; run pnpm prepare:redirects');
else await writeFile(target, output);
console.log(`Verified ${rules.size} compatibility redirects and ${migration.routes.length} legacy page dispositions`);
